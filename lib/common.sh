###############################################################################
# Colour Support
###############################################################################

if [[ -t 1 ]]; then
    RED='\033[0;31m'
    GREEN='\033[0;32m'
    YELLOW='\033[1;33m'
    BLUE='\033[0;34m'
    CYAN='\033[0;36m'
    NC='\033[0m'
else
    RED=""
    GREEN=""
    YELLOW=""
    BLUE=""
    CYAN=""
    NC=""
fi

###############################################################################
# Global Variables
###############################################################################

VERSION="2.0.0"
START_TIME=$(date +%s)

###############################################################################
# Configuration Loader
###############################################################################

load_config() {

    local CONFIG

    CONFIG="$(dirname "${BASH_SOURCE[0]}")/../conf/zapache.conf"

    if [[ -f "$CONFIG" ]]; then
        # shellcheck source=/dev/null
        source "$CONFIG"
    else
        log_warn "Configuration file not found."
    fi
}

###############################################################################
# Logging Functions
###############################################################################

log_info() {

    echo -e "${BLUE}[INFO ]${NC} $*"

}

log_warn() {

    echo -e "${YELLOW}[WARN ]${NC} $*"

}

log_error() {

    echo -e "${RED}[ERROR]${NC} $*" >&2

}

log_debug() {

    [[ "${DEBUG:-0}" -eq 1 ]] && \
        echo -e "${CYAN}[DEBUG]${NC} $*"

}

###############################################################################
# PASS / FAIL
###############################################################################

pass() {

    printf "%-40s ${GREEN}[PASS]${NC}\n" "$1"

}

fail() {

    printf "%-40s ${RED}[FAIL]${NC}\n" "$1"

}

warn() {

    printf "%-40s ${YELLOW}[WARN]${NC}\n" "$1"

}

###############################################################################
# Error Handling
###############################################################################

die() {

    log_error "$*"
    exit 1

}

###############################################################################
# Command Detection
###############################################################################

command_exists() {

    command -v "$1" >/dev/null 2>&1

}

###############################################################################
# HTTP Client Detection
###############################################################################

detect_http_client() {

    if command_exists curl; then
        HTTP_CLIENT="curl"
        return 0
    fi

    if command_exists wget; then
        HTTP_CLIENT="wget"
        return 0
    fi

    die "Neither curl nor wget is installed."

}

###############################################################################
# Banner
###############################################################################

print_banner() {

cat << EOF

============================================================
               ZApache Monitor Toolkit
------------------------------------------------------------
Version : ${VERSION}
============================================================

EOF

}

###############################################################################
# Version
###############################################################################

show_version() {

    echo "${VERSION}"

}

###############################################################################
# Timer
###############################################################################

execution_time() {

    local END
    END=$(date +%s)

    echo "$((END-START_TIME))"

}

###############################################################################
# Root Check
###############################################################################

check_root() {

    [[ $EUID -eq 0 ]]

}

###############################################################################
# Utility Functions
###############################################################################

separator() {

    printf '%*s\n' "${COLUMNS:-60}" '' | tr ' ' '='

}

title() {

    separator
    echo "$1"
    separator

}
